def _strip_markup(text: str) -> str:
    """Remove rich markup tags like [green]...[/green] and ANSI escapes.

    Uses ``rich.text.Text.from_markup`` rather than an ad-hoc regex so
    legitimate substrings like ``EM`` inside a ULID aren't
    collateral-stripped (the previous regex matched ``[em]`` as the
    rich emphasis tag and could mangle node IDs).
    """
    from rich.text import Text

    text = re.sub(r"\x1b\[[0-9;]*m", "", text)
    try:
        return Text.from_markup(text).plain
    except Exception:  # noqa: BLE001 — fall back if markup is malformed
        return text


@dataclass
class WorkedExample:
    """Runs CLI commands and builds a markdown transcript."""

    root: Path
    runner: CliRunner = field(default_factory=CliRunner)
    transcript: list[str] = field(default_factory=list)
    failures: list[str] = field(default_factory=list)

    def section(self, heading: str, narrative: str = "") -> None:
        """Add a section heading + optional narrative."""
        self.transcript.append(f"\n## {heading}\n")
        if narrative:
            self.transcript.append(f"{narrative}\n")

    def run(
        self, args: list[str], *, input: str | None = None, expect_fail: bool = False,
    ) -> str:
        """Run a CLI command, record it, return the output."""
        cmd_str = "latris " + " ".join(args)
        result = self.runner.invoke(app, args, input=input)
        output = _strip_markup(result.output).strip()

        self.transcript.append(f"### `{cmd_str}`\n")
        if output:
            self.transcript.append(f"```\n{output}\n```\n")
        else:
            self.transcript.append("```\n(no output)\n```\n")

        if not expect_fail and result.exit_code != 0:
            self.failures.append(f"FAIL (exit {result.exit_code}): {cmd_str}\n{output}")

        return output

    def note(self, text: str) -> None:
        """Add a narrative note between commands."""
        self.transcript.append(f"_{text}_\n")

    def write_transcript(self, path: Path) -> None:
        """Write accumulated transcript as markdown."""
        header = (
            "# Worked Example Transcript\n\n"
            "Auto-generated by `worked_example/worked_example.py`. "
            "Do not edit by hand — rerun the script to regenerate.\n\n"
            "This transcript demonstrates every CLI command in the current "
            "version of `latris`, exercised against a sample project.\n"
        )
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(
            header + "\n".join(self.transcript) + "\n",
            encoding="utf-8",
            newline="",
        )


